/// A template's bytes.
pub(crate) fn bytes(hex: &str) -> Vec<u8> {
    (0..hex.len() / 2)
        .map(|at| u8::from_str_radix(&hex[at * 2..at * 2 + 2], 16).unwrap_or(0))
        .collect()
}
