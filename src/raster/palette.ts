import { Color } from './color.js';

export class Palette {
  declare _nearest: any;
  declare _palette: any;
  declare static PALETTE16: any;
  declare static PALETTE2: any;
  declare static PALETTEWIN16: any;
  declare static PALETTEWIN256: any;
  constructor(colors) {
    this._palette = colors;
    this._nearest = {};
  }

  nearestColor(color) {
    color = new Color(color);
    const r = color.red;
    const g = color.green;
    const b = color.blue;
    return this.nearestColors(r, g, b, 1)[0];
  }

  nearestIndex(r, g, b) {
    return this.nearestColors(r, g, b, 1)[0].index;
  }

  toRGBA(index) {
    return (
      ((this._palette[index][0] << 24) |
        (this._palette[index][1] << 16) |
        (this._palette[index][2] << 8) |
        0x000000ff) >>>
      0
    );
  }

  toABGR(index) {
    return (
      (this._palette[index][0] |
        (this._palette[index][1] << 8) |
        (this._palette[index][2] << 16) |
        0x000000ff) >>>
      0
    );
  }

  /**
   * Returns the two nearest colors for the current palette and given color.
   *
   * It also returns their distance.
   */
  nearestColors(r, g, b, count = 1) {
    // Create an initial array of size count
    let color: any = new Color(r, g, b);
    color = color.value;

    if (this._nearest[color]) {
      return this._nearest[color];
    }

    let ret = [
      {
        distance: 0xfffffff,
        color: color,
        hex: color.toString(16).padStart(6, '0'),
      },
    ];

    for (let i = 1; i < count; i++) {
      ret.push(ret[0]);
    }

    for (let i = 0; i < this._palette.length; i++) {
      const target = this._palette[i];
      const r2 = target[0];
      const g2 = target[1];
      const b2 = target[2];

      const distance = Math.pow(r - r2, 2) + Math.pow(g - g2, 2) + Math.pow(b - b2, 2);

      const compiled = (target[0] << 16) | (target[1] << 8) | target[2];
      const entry = {
        r: r2,
        g: g2,
        b: b2,
        distance: distance,
        color: compiled,
        hex: compiled.toString(16).padStart(6, '0'),
        index: i,
      };

      // Find a position to place this
      for (let j = 0; j < ret.length; j++) {
        if (ret[j].distance >= distance) {
          // Push this entry down
          ret = ret.slice(0, j).concat([entry]).concat(ret.slice(j));
          ret.pop();
          break;
        }
      }

      if (distance == 0) {
        break;
      }
    }

    // Cache the result
    this._nearest[color] = ret;

    // Return the selection
    return ret;
  }
}

