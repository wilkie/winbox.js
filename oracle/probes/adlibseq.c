/*
 * A MIDI file played by MCI's sequencer, MCISEQ.DRV, on the installation
 * with a sound card (`--display vgasound`): through the MIDI Mapper to the
 * Ad Lib, as a program playing its music with mciSendString does. As
 * `adlibout`, what DOSBox's OPL was sent is captured as it plays
 * (`record.mjs --capture`) into `oracle/fixtures/opl/`, after the probe's
 * `capture` record and a pause.
 *
 * The probe writes its own file, `ADLIBSEQ.MID`: two seconds at 120 beats
 * a minute, eight eighth notes on channel 13 (piano), two half notes on
 * channel 14 (patch 32), a bass drum and a snare on the beats and a closed
 * hi-hat on the eighths on channel 16 -- the channels the mapper's "Ad Lib"
 * setup sends to the Ad Lib. It begins with the sequencer-specific event
 * `00 00 41`, which MCISEQ takes for a file written for the default setup
 * (`MCISEQ.DRV` seg3 `18de`-`191c`): without it MCISEQ warns, in a box,
 * that the file may not play correctly.
 *
 * * `mci`: the command's number, in order, and the command string; what
 *   mciSendString answered, in hex, and the text it gave back, in brackets.
 * * `at`: when each command was sent, in milliseconds after the first.
 *   Not an answer.
 */

